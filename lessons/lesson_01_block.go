// 什么是区块？
// ==========
// 区块就像是区块链中的一页纸，每页纸记录了一些信息，并且通过哈希值
// 与前一页纸连接起来，形成一条不可篡改的链条。
//
// 一个区块包含哪些信息？
// ====================
// 1. Index (索引): 区块在区块链中的位置，第0个是创世区块
// 2. Timestamp (时间戳): 区块创建的时间
// 3. Data (数据): 区块存储的内容（可以是交易记录、合约调用等）
// 4. PreviousHash (前一个区块的哈希): 指向前一个区块的"指针"
// 5. Hash (当前区块的哈希): 当前区块的唯一标识
// 6. Nonce (随机数): 挖矿时使用的数值，用于找到符合条件的哈希
// ============================================================================

//go:build lesson01

package main

import (
	"fmt"
	"time"
)

// Block 定义区块的结构体
// 结构体中的 `json:"index"` 是 Go 的标签（tag），用于 JSON 序列化
type Block struct {
	Index        int64  // 区块编号：从0开始递增
	Timestamp    int64  // 时间戳：使用 Unix 时间戳（秒数）
	Data         string // 数据：本课程中存储简单的字符串，后续课程会改为交易
	PreviousHash string // 前一个区块的哈希：这是区块链"链"的关键
	Hash         string // 当前区块的哈希：区块的唯一指纹
	Nonce        int64  // 随机数：用于工作量证明（挖矿），课程3会详细讲解
}

// NewBlock 创建一个新区块
//
// 参数说明：
//   - index: 区块的编号
//   - data: 区块要存储的数据
//   - previousHash: 前一个区块的哈希值
//
// 返回值：
//   - *Block: 创建好的区块指针
//
// 为什么返回指针？
// ================
// 在 Go 中，结构体可能很大。返回指针（*Block）只返回一个内存地址，
// 比返回整个结构体更高效，后续操作时也直接修改原数据，而不是复制副本。
func NewBlock(index int64, data string, previousHash string) *Block {
	// 使用 := 创建新变量并自动推断类型
	block := &Block{
		Index:        index,           // 区块编号
		Timestamp:    time.Now().Unix(), // 获取当前时间戳（秒）
		Data:         data,             // 存储的数据
		PreviousHash: previousHash,     // 前一个区块的哈希
	}

	// 注意：这里暂时用空字符串代替哈希
	// 实际的哈希计算会在第二课讲解
	block.Hash = ""

	return block
}

// String 实现 Stringer 接口，让 fmt.Println 可以漂亮地打印区块
// 这是一个 Go 的惯例：实现 String() 方法后，打印结构体时会调用它
func (b *Block) String() string {
	return fmt.Sprintf(
		"区块 #%d\n"+
			"  时间: %s\n"+
			"  数据: %s\n"+
			"  前哈希: %s\n"+
			"  哈希: %s\n"+
			"  Nonce: %d",
		b.Index,
		time.Unix(b.Timestamp, 0).Format("2006-01-02 15:04:05"), // Go 的时间格式是固定的
		b.Data,
		b.PreviousHash,
		b.Hash,
		b.Nonce,
	)
}

// PrintBlock 打印区块信息的辅助函数
func PrintBlock(block *Block) {
	fmt.Println("========================================")
	fmt.Println(block)
	fmt.Println("========================================")
}

// ============================================================================
// 主函数：演示区块的创建和使用
// ============================================================================
func main() {
	fmt.Println("📚 第一课：区块结构")
	fmt.Println("========================================")

	// 1. 创建创世区块（Genesis Block）
	// 创世区块是区块链的第一个区块，它的 PreviousHash 通常设为 "0"
	fmt.Println("\n🔹 创建创世区块...")
	genesis := NewBlock(
		0,       // 索引为0
		"创世区块：区块链的起点",
		"0",     // 前哈希设为"0"表示没有前一个区块
	)
	PrintBlock(genesis)

	// 2. 创建第二个区块
	// 第二个区块的 PreviousHash 指向创世区块的 Hash
	fmt.Println("\n🔹 创建第二个区块...")
	block1 := NewBlock(
		1,                     // 索引递增
		"Alice 转账给 Bob 50 BTC",
		genesis.Hash,          // 指向创世区块
	)
	PrintBlock(block1)

	// 3. 创建第三个区块
	fmt.Println("\n🔹 创建第三个区块...")
	block2 := NewBlock(
		2,
		"Bob 转账给 Charlie 30 BTC",
		block1.Hash,           // 指向前一个区块
	)
	PrintBlock(block2)

	// ============================================================================
	// 本课小结
	// ============================================================================
	// ✅ 我们学习了：
	// 1. 区块的结构包含索引、时间戳、数据、前哈希、哈希、Nonce
	// 2. 区块通过 PreviousHash 连接在一起
	// 3. 创世区块是区块链的第一个区块，PreviousHash 为 "0"
	//
	// ❓ 思考题：
	// 1. 为什么每个区块都要记录前一个区块的哈希？
	// 2. 如果有人篡改了区块1的数据，会发生什么？（提示：看哈希值）
	//
	// 🔜 下一课：哈希计算 - 学习如何为区块生成唯一的哈希值
	// ============================================================================
	fmt.Println("\n✅ 第一课完成！下一课将学习如何计算区块的哈希值。")
}