// 目标：理解哈希是什么，以及如何为区块生成哈希值
// 前置知识：第一课 - 区块结构
// 学习时长：20分钟
//
// 什么是哈希？
// ============
// 哈希（Hash）是将任意长度的数据转换为固定长度的字符串的函数。
// 可以把它理解为"数据指纹"——不同的数据会产生不同的哈希值。
//
// 为什么区块链需要哈希？
// =====================
// 1. 唯一标识：每个区块的哈希都是唯一的
// 2. 数据完整性：哪怕改一个字符，哈希值也会完全改变
// 3. 链接区块：通过 PreviousHash 将区块连接成链条
//
// 常见的哈希算法
// =============
// - MD5: 已不安全（容易碰撞）
// - SHA-1: 已不安全
// - SHA-256: 比特币使用，较安全
// - SHA-3: 更新的标准
//
// 本课程使用 SHA-256
// ====================
// SHA-256 输出 256 位（32 字节），用十六进制表示是 64 个字符
// 示例：a1b2c3d4...（共64个字符，由0-9和a-f组成）
// ============================================================================

//go:build lesson02

package main

import (
	"crypto/sha256" // 导入 SHA-256 哈希算法
	"encoding/hex"  // 用于将字节数组转换为十六进制字符串
	"fmt"
	"time"
)

// Block 区块结构（与第一课相同）
type Block struct {
	Index        int64
	Timestamp    int64
	Data         string
	PreviousHash string
	Hash         string
	Nonce        int64
}

// ============================================================================
// 核心方法：calculateHash
// ============================================================================
// 这个方法是哈希计算的核心，它会将区块的所有信息组合成一个字符串，
// 然后用 SHA-256 计算出哈希值。
//
// 为什么这样组合？
// ================
// 我们需要将区块的所有信息都包含在哈希计算中，这样：
// 1. 改变任何数据都会导致哈希改变
// 2. 相同的数据会产生相同的哈希（确定性）
// 3. 无法从哈希反推出原始数据（单向性）
//
// 哈希输入的顺序重要吗？
// =====================
// 是的！顺序不同会产生不同的哈希。
// 比如 "A+B" 和 "B+A" 的哈希是不同的。
// 因此我们必须固定一个统一的顺序。
// ============================================================================

func (b *Block) calculateHash() string {
	// 第一步：将所有字段拼接成一个字符串
	//
	// Go 中的 + 操作符可以连接字符串
	// 但要注意性能：如果拼接很多字符串，建议使用 strings.Builder
	// 这里的字段不多，直接用 + 就可以了

	record := fmt.Sprintf("%d%d%s%s%d",
		b.Index,        // 区块索引
		b.Timestamp,    // 时间戳
		b.Data,         // 数据
		b.PreviousHash, // 前一个区块的哈希
		b.Nonce,        // 随机数（用于挖矿，第四课会讲）
	)

	// 第二步：创建 SHA-256 哈希对象
	// sha256.New() 返回一个 hash.Hash 接口
	h := sha256.New()

	// 第三步：将数据写入哈希对象
	// Write 方法接收 []byte 类型，所以需要将字符串转为字节数组
	h.Write([]byte(record))

	// 第四步：获取哈希结果
	// Sum(nil) 返回哈希值的字节数组（32字节）
	hashed := h.Sum(nil)

	// 第五步：将字节数组转换为十六进制字符串
	// 这样我们就能看到一个可读的 64 字符的哈希值
	hashString := hex.EncodeToString(hashed)

	return hashString
}

// NewBlock 创建新区块并计算哈希
// 与第一课的区别是：这里会立即计算哈希值
func NewBlock(index int64, data string, previousHash string) *Block {
	block := &Block{
		Index:        index,
		Timestamp:    time.Now().Unix(),
		Data:         data,
		PreviousHash: previousHash,
		Nonce:        0,
	}

	// 立即计算哈希值
	block.Hash = block.calculateHash()

	return block
}

// ============================================================================
// 演示哈希的特性
// ============================================================================

// CalculateStringHash 为任意字符串计算哈希（辅助函数）
func CalculateStringHash(input string) string {
	h := sha256.New()
	h.Write([]byte(input))
	return hex.EncodeToString(h.Sum(nil))
}

func main() {
	fmt.Println("📚 第二课：哈希计算")
	fmt.Println("========================================")

	// -------------------------------------------------------------------------
	// 演示1：不同数据产生不同哈希
	// -------------------------------------------------------------------------
	fmt.Println("\n🔹 演示1：哈希的唯一性")
	fmt.Println("----------------------------------------")

	texts := []string{
		"Hello",
		"hello",  // 大小写不同
		"Hello!", // 多了一个字符
	}

	for _, text := range texts {
		hash := CalculateStringHash(text)
		fmt.Printf("'%s' 的哈希: %s\n", text, hash)
	}
	fmt.Println("→ 结论：只要数据有一点点不同，哈希就完全不同！")

	// -------------------------------------------------------------------------
	// 演示2：相同数据产生相同哈希
	// -------------------------------------------------------------------------
	fmt.Println("\n🔹 演示2：哈希的确定性")
	fmt.Println("----------------------------------------")

	text := "Hello World"
	hash1 := CalculateStringHash(text)
	hash2 := CalculateStringHash(text)

	fmt.Printf("第一次计算: %s\n", hash1)
	fmt.Printf("第二次计算: %s\n", hash2)
	fmt.Printf("两者相等: %v\n", hash1 == hash2)
	fmt.Println("→ 结论：相同的数据每次计算都会得到相同的哈希！")

	// -------------------------------------------------------------------------
	// 演示3：创建一个完整的区块
	// -------------------------------------------------------------------------
	fmt.Println("\n🔹 演示3：为区块计算哈希")
	fmt.Println("----------------------------------------")

	genesis := NewBlock(
		0,
		"创世区块",
		"0",
	)

	fmt.Printf("区块 #%d\n", genesis.Index)
	fmt.Printf("数据: %s\n", genesis.Data)
	fmt.Printf("前哈希: %s\n", genesis.PreviousHash)
	fmt.Printf("计算出的哈希: %s\n", genesis.Hash)

	// -------------------------------------------------------------------------
	// 演示4：改变数据会改变哈希（这是区块链安全的基础！）
	// -------------------------------------------------------------------------
	fmt.Println("\n🔹 演示4：数据篡改检测")
	fmt.Println("----------------------------------------")

	block := NewBlock(1, "Alice 转账给 Bob 50 BTC", genesis.Hash)
	fmt.Printf("原始哈希: %s\n", block.Hash)

	// 假设有人想篡改交易金额
	block.Data = "Alice 转账给 Bob 5000 BTC"  // 把 50 改成 5000
	newHash := block.calculateHash()

	fmt.Printf("篡改后数据: %s\n", block.Data)
	fmt.Printf("篡改后哈希: %s\n", newHash)
	fmt.Printf("哈希相等: %v\n", block.Hash == newHash)
	fmt.Println("→ 结论：篡改数据会导致哈希改变，这能被检测出来！")

	// -------------------------------------------------------------------------
	// 演示5：区块通过哈希链接成链
	// -------------------------------------------------------------------------
	fmt.Println("\n🔹 演示5：区块链的链式结构")
	fmt.Println("----------------------------------------")

	block0 := NewBlock(0, "创世区块", "0")
	block1 := NewBlock(1, "第一笔交易", block0.Hash)
	block2 := NewBlock(2, "第二笔交易", block1.Hash)
	block3 := NewBlock(3, "第三笔交易", block2.Hash)

	fmt.Printf("区块0 哈希: %s\n", block0.Hash[:16]+"...")
	fmt.Printf("区块1 前哈希: %s\n", block1.PreviousHash[:16]+"...")
	fmt.Printf("区块2 前哈希: %s\n", block2.PreviousHash[:16]+"...")
	fmt.Printf("区块3 前哈希: %s\n", block3.PreviousHash[:16]+"...")

	fmt.Println("\n→ 每个区块的 PreviousHash 都指向上一区块的 Hash！")

	// ============================================================================
	// 本课小结
	// ============================================================================
	// ✅ 我们学习了：
	// 1. 哈希是将数据转换为固定长度字符串的函数
	// 2. SHA-256 是常用的安全哈希算法
	// 3. 哈希具有唯一性、确定性、单向性
	// 4. 改变数据会改变哈希，这是区块链安全的基石
	// 5. 区块通过哈希连接成链条
	//
	// ❓ 思考题：
	// 1. SHA-256 的输出长度是多少位？多少字节？多少个十六进制字符？
	// 2. 如果两个不同的数据产生了相同的哈希，这叫什么？
	// 3. 为什么用哈希链接区块而不是直接用索引？
	//
	// 🔜 下一课：挖矿与工作量证明 - 学习如何找到符合条件的哈希
	// ============================================================================
	fmt.Println("\n✅ 第二课完成！下一课将学习挖矿与工作量证明。")
}